-- Use only if your managed PostgreSQL account cannot create this table via
-- SQLAlchemy Base.metadata.create_all() on backend startup.
-- Run this once in Supabase SQL Editor before enabling duplicate detection.
CREATE TABLE IF NOT EXISTS invoice_scans (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE CASCADE,
    content_sha256 VARCHAR(64) NOT NULL,
    scanned_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_invoice_scans_shop_hash
    ON invoice_scans (shop_id, content_sha256);
